import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createInterface} from 'node:readline';
import {fileURLToPath} from 'node:url';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const isolated=mkdtempSync(join(tmpdir(),'kennect-mcp-test-'));
test.after(()=>rmSync(isolated,{recursive:true,force:true}));
test('MCP discovers browser tools and rejects invalid calls',async()=>{
 const p=spawn(process.execPath,[fileURLToPath(new URL('./server.mjs',import.meta.url))],{stdio:['pipe','pipe','pipe'],env:{...process.env,KENNECT_BROWSER_BRIDGE_DIR:join(isolated,'bridge'),KENNECT_BROWSER_PROFILE:join(isolated,'profile')}});
 const pending=new Map();let id=0;const lines=createInterface({input:p.stdout});
 lines.on('line',line=>{const m=JSON.parse(line);pending.get(m.id)?.(m);pending.delete(m.id)});
 p.on('exit',()=>{for(const resolve of pending.values())resolve({error:{message:'Server exited before responding'}});pending.clear()});
 const call=(method,params={})=>new Promise(resolve=>{const n=++id;const timer=setTimeout(()=>resolve({error:{message:'Timed out'}}),12000);pending.set(n,m=>{clearTimeout(timer);resolve(m)});p.stdin.write(JSON.stringify({jsonrpc:'2.0',id:n,method,params})+'\n')});
 try{
  const init=await call('initialize',{protocolVersion:'2024-11-05',capabilities:{},clientInfo:{name:'test',version:'1'}});assert.equal(init.result?.serverInfo?.name,'kennect-browser');
  const list=await call('tools/list');assert.ok(list.result.tools.some(t=>t.name==='browser_snapshot'));assert.ok(list.result.tools.some(t=>t.name==='browser_click'));
  const zoomTool=list.result.tools.find(t=>t.name==='browser_zoom');
  assert.match(zoomTool.description,/cropped screenshot/i);
  assert.match(zoomTool.description,/not a zoom/i);
  assert.match(zoomTool.description,/does not change/i);
  assert.match(zoomTool.description,/full-page screenshot/i);
  const names=list.result.tools.map(t=>t.name);assert.ok(names.includes('browser_profiles'));assert.ok(names.includes('browser_set_default_profile'));assert.ok(names.includes('browser_download'));assert.ok(names.includes('browser_download_status'));
  const missingDownload=await call('tools/call',{name:'browser_download',arguments:{}});assert.equal(missingDownload.error.code,-32602);
  const badDownloadId=await call('tools/call',{name:'browser_download_status',arguments:{downloadId:'x'}});assert.equal(badDownloadId.error.code,-32602);
  const openTab=list.result.tools.find(t=>t.name==='browser_open_tab');assert.ok(openTab.inputSchema.properties.groupTitle);assert.ok(openTab.inputSchema.properties.groupColor);assert.ok(openTab.inputSchema.properties.windowId);
  assert.ok(names.includes('browser_windows'));
  assert.ok(names.includes('browser_open_window'));
  assert.ok(names.includes('browser_update_window'));
  assert.ok(names.includes('browser_close_window'));
  const windowsTool=list.result.tools.find(t=>t.name==='browser_windows');
  assert.equal(windowsTool.annotations.readOnlyHint,true);
  const openWindow=list.result.tools.find(t=>t.name==='browser_open_window');
  assert.ok(openWindow.inputSchema.properties.name);
  assert.deepEqual(openWindow.inputSchema.required,['url']);
  const updateWindow=list.result.tools.find(t=>t.name==='browser_update_window');
  assert.deepEqual(updateWindow.inputSchema.properties.state.enum,['normal','minimized','maximized','fullscreen']);
  const bothTargets=await call('tools/call',{name:'browser_resize',arguments:{width:800,height:600,tabId:'1',windowId:2}});
  assert.equal(bothTargets.error.code,-32602);
  const badState=await call('tools/call',{name:'browser_update_window',arguments:{windowId:1,state:'bogus'}});
  assert.equal(badState.error.code,-32602);
  const claimWithoutName=await call('tools/call',{name:'browser_open_window',arguments:{url:'https://example.com/',claim:true}});
  assert.equal(claimWithoutName.error.code,-32602);
  const unknownWindowArg=await call('tools/call',{name:'browser_open_window',arguments:{url:'https://example.com/',bogus:1}});
  assert.equal(unknownWindowArg.error.code,-32602);
  assert.ok(names.includes('browser_ensure'));
  const ensureTool=list.result.tools.find(t=>t.name==='browser_ensure');
  assert.equal(ensureTool.inputSchema.properties.profile,undefined);
  assert.equal(ensureTool.annotations.readOnlyHint,false);
  assert.deepEqual(ensureTool.inputSchema.properties.timeoutMs,{type:'integer',minimum:5000,maximum:60000});
  const badEnsureTimeout=await call('tools/call',{name:'browser_ensure',arguments:{timeoutMs:1000}});
  assert.equal(badEnsureTimeout.error.code,-32602);
  const emptyProfileDir=await call('tools/call',{name:'browser_ensure',arguments:{profileDirectory:''}});
  assert.equal(emptyProfileDir.error.code,-32602);
  const unknownEnsureArg=await call('tools/call',{name:'browser_ensure',arguments:{bogus:1}});
  assert.equal(unknownEnsureArg.error.code,-32602);
  assert.ok(names.includes('browser_emulate_device'));
  assert.ok(names.includes('browser_clear_device_emulation'));
  const emulateTool=list.result.tools.find(t=>t.name==='browser_emulate_device');
  assert.deepEqual(emulateTool.inputSchema.required,['width','height']);
  assert.deepEqual(emulateTool.inputSchema.properties.orientation.enum,['portraitPrimary','portraitSecondary','landscapePrimary','landscapeSecondary']);
  assert.equal(emulateTool.inputSchema.properties.deviceScaleFactor.minimum,1);
  assert.equal(emulateTool.inputSchema.properties.deviceScaleFactor.maximum,4);
  const badEmulationWidth=await call('tools/call',{name:'browser_emulate_device',arguments:{width:99,height:844}});
  assert.equal(badEmulationWidth.error.code,-32602);
  const badEmulationDpr=await call('tools/call',{name:'browser_emulate_device',arguments:{width:390,height:844,deviceScaleFactor:5}});
  assert.equal(badEmulationDpr.error.code,-32602);
  const badEmulationOrientation=await call('tools/call',{name:'browser_emulate_device',arguments:{width:390,height:844,orientation:'sideways'}});
  assert.equal(badEmulationOrientation.error.code,-32602);
  const unknownEmulationArg=await call('tools/call',{name:'browser_emulate_device',arguments:{width:390,height:844,bogus:1}});
  assert.equal(unknownEmulationArg.error.code,-32602);
  const clearEmulation=list.result.tools.find(t=>t.name==='browser_clear_device_emulation');
  assert.ok(clearEmulation.inputSchema.properties.tabId);
  const profiles=await call('tools/call',{name:'browser_profiles',arguments:{}});assert.equal(profiles.result.isError,false);assert.deepEqual(JSON.parse(profiles.result.content[0].text),{default:null,profiles:[]});
  const unknownProfile=await call('tools/call',{name:'browser_set_default_profile',arguments:{profile:'chrome:Default:aaaaaa'}});assert.equal(unknownProfile.result.isError,true);assert.match(unknownProfile.result.content[0].text,/Unknown browser profile/);
  const missingProfile=await call('tools/call',{name:'browser_set_default_profile',arguments:{}});assert.equal(missingProfile.error.code,-32602);
  const requestedProfile=await call('tools/call',{name:'browser_tabs',arguments:{profile:'chrome:Default:aaaaaa'}});assert.equal(requestedProfile.result.isError,true);assert.match(requestedProfile.result.content[0].text,/Unknown browser profile/);
  if(process.env.KENNECT_BROWSER_LIVE_TESTS==='1'){const read=await call('tools/call',{name:'browser_snapshot',arguments:{}});assert.equal(read.result.isError,false);assert.match(read.result.content[0].text,/zhipin\.com/);}
  const bad=await call('tools/call',{name:'browser_navigate',arguments:{url:'file:///etc/passwd'}});assert.equal(bad.result.isError,true);
  const unknown=await call('tools/call',{name:'shell',arguments:{}});assert.equal(unknown.error.code,-32602);
  const invalid=await call('tools/call',{name:'browser_click',arguments:{nodeId:'bad'}});assert.equal(invalid.error.code,-32602);
 }finally{p.kill();lines.close()}
});
